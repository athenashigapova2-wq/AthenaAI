"""Сборка инструментов для конкретного пользователя.

Ключевой приём: user_id замыкается внутри функции и не попадает
в схему, которую видит модель. Модель физически не может запросить
чужие данные — у неё нет такого параметра.
"""

from langchain_core.tools import StructuredTool

from app.tools import profile as profile_tools


def build_tools(user_id: str) -> list[StructuredTool]:
    """Возвращает инструменты, привязанные к одному пользователю."""

    def get_my_profile() -> dict:
        """Возвращает профиль пользователя: возраст, пол, рост, вес, цель,
        целевые калории и БЖУ, аллергии, любимые и нелюбимые продукты.
        Вызывай, когда нужны персональные данные для расчёта или совета."""
        return profile_tools.get_profile(user_id)

    return [
        StructuredTool.from_function(
            func=get_my_profile,
            name="get_my_profile",
            description=(
                "Профиль пользователя: возраст, пол, рост, вес, цель, "
                "целевые калории и БЖУ, аллергии, предпочтения в еде. "
                "Вызывай перед любым персональным советом по питанию."
            ),
        ),
    ]